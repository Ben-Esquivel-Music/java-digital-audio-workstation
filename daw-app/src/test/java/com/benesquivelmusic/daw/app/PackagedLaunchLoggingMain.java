package com.benesquivelmusic.daw.app;

import java.net.URL;
import java.net.URLClassLoader;
import java.nio.file.Path;
import java.util.logging.Level;
import java.util.logging.LogManager;
import java.util.logging.Logger;

/**
 * The child-JVM side of {@code PackagedLaunchLoggingTest} and of the
 * packaged-artifact proof (story 336, Technical Notes): it sets logging up
 * exactly as the packaged launcher does — {@link DawLauncher#prepareLaunch}
 * on the production settings directory — and then writes what the parent
 * looks for in the log file: an INFO line, a FINE line that must not reach
 * the file, optionally a record whose exception only its closed plugin JAR
 * could format (its path is the first argument), and an uncaught failure on a
 * {@code daw-take-storage} virtual thread. It uses only the JDK and
 * {@code daw.*} modules, so it also runs on the jlink image.
 */
public final class PackagedLaunchLoggingMain {

    /** The jar-only exception's class, generated by {@code JarOnlyExceptions}. */
    private static final String JAR_ONLY_EXCEPTION = "com.example.sneaky.LicenceException";

    private PackagedLaunchLoggingMain() {
    }

    /**
     * @param args optionally, the path of the JAR holding the jar-only exception
     * @throws Exception if the child cannot run
     */
    public static void main(String[] args) throws Exception {
        DawLauncher.prepareLaunch(DawLauncher.userSettingsDirectory());
        System.out.println("log manager: " + LogManager.getLogManager().getClass().getName());
        System.out.println("settings: " + DawLauncher.userSettingsDirectory());

        Logger logger = Logger.getLogger(PackagedLaunchLoggingMain.class.getName());
        logger.setLevel(Level.FINE);
        logger.info("packaged launch: an INFO line");
        logger.fine("packaged launch: a FINE line");
        if (args.length > 0) {
            logger.log(Level.WARNING, "A removed plugin failed while it was disposed", loadThenClose(Path.of(args[0])));
        }
        Thread failing = Thread.ofVirtual().name("daw-take-storage").start(PackagedLaunchLoggingMain::failToStore);
        failing.join();
        System.out.println("done");
        System.exit(0);
    }

    private static void failToStore() {
        throw new IllegalStateException("disk gone");
    }

    /** Loads the jar-only exception with a class loader of its own, then closes the loader. */
    private static RuntimeException loadThenClose(Path jar) throws Exception {
        URLClassLoader loader = new URLClassLoader(new URL[] {jar.toUri().toURL()},
                PackagedLaunchLoggingMain.class.getClassLoader());
        try {
            return (RuntimeException) loader.loadClass(JAR_ONLY_EXCEPTION).getConstructor().newInstance();
        } finally {
            loader.close();
        }
    }
}
